"""Responsive Chromium QA for the Bulb Brightness Check and shared-room handoff."""
import functools, http.server, os, socketserver, threading
from playwright.sync_api import sync_playwright

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "website")
class Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *args): pass
server = socketserver.TCPServer(("127.0.0.1", 0), functools.partial(Quiet, directory=ROOT))
threading.Thread(target=server.serve_forever, daemon=True).start()
BASE = "http://127.0.0.1:%d/" % server.server_address[1]
failures = []
def check(name, ok, detail=""):
    print(("PASS " if ok else "FAIL ") + name + ("" if ok else " | " + str(detail)[:300]))
    if not ok: failures.append(name)

with sync_playwright() as p:
    browser = p.chromium.launch(args=["--no-sandbox"])
    for width in (320, 390, 1280):
        context = browser.new_context(viewport={"width": width, "height": 900})
        context.route("**/*", lambda route: route.continue_() if route.request.url.startswith(BASE) else route.abort())
        page = context.new_page()
        errors = []
        page.on("pageerror", lambda e: errors.append(str(e)))
        page.goto(BASE + "bulb-brightness-check.html", wait_until="load")
        check("page loads at %dpx" % width, page.locator("h1").inner_text() == "Bulb Brightness Check")
        check("no horizontal overflow at %dpx" % width, page.evaluate("document.documentElement.scrollWidth <= window.innerWidth"))
        check("lumens starts blank at %dpx" % width, page.input_value("#lumens-per-bulb") == "" and page.locator("#brightness-result").inner_text() == "" and page.locator("#brightness-status").inner_text() == "")
        page.fill("#fixture-count","2"); page.fill("#bulbs-per-fixture","3"); page.select_option("#room-type","kitchen")
        page.fill("#room-area","24"); page.select_option("#area-unit","m2"); page.click("button[type=submit]")
        check("blank lumens shows a neutral status line under the Calculate button, not a zero or result, at %dpx" % width, page.locator("#brightness-status").inner_text() == "Enter the lumens printed on the bulb box to see your totals." and page.locator("#brightness-result").inner_text() == "" and page.locator("#brightness-status").get_attribute("role") == "status")
        page.fill("#lumens-per-bulb","800"); page.click("button[type=submit]")
        result = page.locator("#brightness-result").inner_text()
        check("kitchen example and hand-computed fixture/total arithmetic at %dpx" % width, "1,000+ lumens per fixture" in result and "2,400 lumens per fixture" in result and "4,800 lumens" in result, result)
        check("area ratio is plain lumens per m², not lux at %dpx" % width, "200 lumens per m² of floor" in result and "not lux or foot-candles" in result, result)
        page.select_option("#room-type","living-room"); page.click("button[type=submit]")
        check("living-room source example is 400–800 and explicitly not a target at %dpx" % width, "400–800 lumens per fixture" in page.locator("#brightness-result").inner_text() and "not a target" in page.locator("#brightness-result").inner_text())
        page.select_option("#room-type",""); page.fill("#room-area",""); page.click("button[type=submit]")
        result = page.locator("#brightness-result").inner_text()
        check("no room reference and no area ratio when not entered at %dpx" % width, "ENERGY STAR fixture example" not in result and "floor-area ratio" not in result)
        page.fill("#lumens-per-bulb","0"); page.click("button[type=submit]")
        check("zero lumens is rejected and never shown as a result at %dpx" % width, "greater than zero" in page.locator("#brightness-error").inner_text() and page.locator("#brightness-result").inner_text() == "" and page.locator("#brightness-status").inner_text() == "")
        check("article and source links are present at %dpx" % width, page.locator('a[href*="better-evening-home-lighting"]').count() == 1 and page.locator('a[href*="ES_Fixtures_FactSheet"]').count() == 1)
        page.locator("#room-type").focus(); page.keyboard.press("Tab")
        check("keyboard moves from room type to fixture count at %dpx" % width, page.evaluate("document.activeElement.id === 'fixture-count'"))
        check("no browser errors at %dpx" % width, not errors, errors)
        context.close()

    context = browser.new_context(viewport={"width":390,"height":844})
    context.route("**/*", lambda route: route.continue_() if route.request.url.startswith(BASE) else route.abort())
    home = context.new_page()
    home.goto(BASE + "home-project-calculator.html", wait_until="domcontentloaded")
    home.locator("#room-root summary").click()
    home.select_option("#room-unit","m")
    home.fill("#room-length","3"); home.fill("#room-width","1.1")
    with home.expect_popup() as popup_info:
        home.locator('button[data-target="bulb-brightness"]').click()
    popup = popup_info.value
    popup.wait_for_load_state("load")
    check("shared room pre-fills exact 3.3 m² in Bulb Brightness", popup.input_value("#room-area") == "3.3" and popup.input_value("#area-unit") == "m2", popup.input_value("#room-area"))
    check("shared-room handoff note is visible", "copied from your shared room" in popup.locator("#shared-room-note").inner_text())
    context.close()
    for width in (320, 390, 1280):
        context = browser.new_context(viewport={"width":width,"height":900})
        context.route("**/*", lambda route: route.continue_() if route.request.url.startswith(BASE) else route.abort())
        page = context.new_page()
        errors = []
        page.on("pageerror", lambda e: errors.append(str(e)))
        page.goto(BASE + "room-lighting-planner.html", wait_until="load")
        check("room lighting planner loads at %dpx" % width, page.locator("h1").inner_text() == "Room Lighting Planner")
        check("room lighting planner has no horizontal overflow at %dpx" % width, page.evaluate("document.documentElement.scrollWidth <= window.innerWidth"))
        check("US is explicitly unsupported at %dpx" % width, "United States is not supported" in page.locator("body").inner_text())
        page.select_option("#rl-source","uk")
        check("UK source identity and population are shown at %dpx" % width, "Thomas Pocklington Trust" in page.locator("#rl-source-detail").inner_text() and "sight loss" in page.locator("#rl-source-detail").inner_text() and "page 22" in page.locator("#rl-source-detail").inner_text())
        page.select_option("#rl-target","uk-kitchen")
        page.fill("#rl-area","20"); page.select_option("#rl-area-unit","m2"); page.fill("#rl-bulb-lumens","800")
        page.click("#rl-form button[type=submit]")
        result = page.locator("#rl-result").inner_text()
        check("UK target range, CoU endpoint formula and bulb rounding at %dpx" % width, "200–300 lx" in result and "200 lx × 20 m² ÷ 0.7 = 5,714.29 lumens" in result and "300 lx × 20 m² ÷ 0.3 = 20,000 lumens" in result and "8–25 bulbs" in result, result)
        check("planning-only notice is visible at %dpx" % width, "not a lighting design" in result and "not a compliance statement" in result)
        page.select_option("#rl-source","canada")
        options = page.locator("#rl-target option").all_text_contents()
        check("Canada options are replaced with its own source rows at %dpx" % width, any("Countertop, sink" in x and "750 lx" in x for x in options) and not any("Kitchen floor" in x for x in options), options)
        page.select_option("#rl-target","ca-kitchen-task"); page.fill("#rl-area","10"); page.fill("#rl-bulb-lumens","")
        page.click("#rl-form button[type=submit]")
        result = page.locator("#rl-result").inner_text()
        check("Canada task value is source-specific and bulb count is withheld when blank at %dpx" % width, "750 lx" in result and "10 m²" in result and "No bulb count shown" in result and "750 lx × 10 m² ÷ 0.7" in result, result)
        page.select_option("#rl-source","malta")
        check("Malta offers its own dwelling rows only at %dpx" % width, page.locator("#rl-target option[value=mt-kitchen]").count() == 1 and page.locator("#rl-target option[value=uk-kitchen]").count() == 0)
        page.select_option("#rl-target","mt-kitchen"); page.click("#rl-form button[type=submit]")
        check("Malta range remains 150–300 lx at %dpx" % width, "150–300 lx" in page.locator("#rl-result").inner_text())
        page.select_option("#rl-source","australia")
        page.select_option("#rl-target","au-bedroom-maintained"); page.fill("#rl-area","15")
        page.click("#rl-form button[type=submit]")
        check("Australia maintained row remains distinct at %dpx" % width, "80 lx" in page.locator("#rl-result").inner_text() and "Table 6" in page.locator("#rl-source-detail").inner_text())
        page.select_option("#rl-target","au-bedroom-initial"); page.click("#rl-form button[type=submit]")
        check("Australia initial row remains distinct at %dpx" % width, "100 lx" in page.locator("#rl-result").inner_text())
        page.select_option("#rl-source","uk"); page.select_option("#rl-target","uk-kitchen")
        page.select_option("#rl-area-unit","ft2"); page.fill("#rl-area","100"); page.click("#rl-form button[type=submit]")
        check("imperial area is explicitly converted to square metres at %dpx" % width, "100 ft² × 0.09290304 = 9.29 m²" in page.locator("#rl-result").inner_text())
        page.fill("#rl-area","0"); page.click("#rl-form button[type=submit]")
        check("zero area is rejected at %dpx" % width, "greater than zero" in page.locator("#rl-error").inner_text() and page.locator("#rl-result").inner_text() == "")
        page.fill("#rl-area","20"); page.fill("#rl-bulb-lumens","0"); page.click("#rl-form button[type=submit]")
        check("zero bulb lumens is rejected at %dpx" % width, "greater than zero" in page.locator("#rl-error").inner_text())
        check("no browser errors at %dpx" % width, not errors, errors)
        context.close()

    context = browser.new_context(viewport={"width":390,"height":844})
    context.route("**/*", lambda route: route.continue_() if route.request.url.startswith(BASE) else route.abort())
    home = context.new_page()
    home.goto(BASE + "home-project-calculator.html", wait_until="domcontentloaded")
    home.locator("#room-root summary").click()
    home.select_option("#room-unit","m")
    home.fill("#room-length","3"); home.fill("#room-width","1.1")
    with home.expect_popup() as popup_info:
        home.locator('button[data-target="room-lighting-planner"]').click()
    popup = popup_info.value
    popup.wait_for_load_state("load")
    check("shared room pre-fills exact 3.3 m² in Room Lighting", popup.input_value("#rl-area") == "3.3" and popup.input_value("#rl-area-unit") == "m2", popup.input_value("#rl-area"))
    popup.select_option("#rl-source","uk"); popup.select_option("#rl-target","uk-kitchen")
    popup.click("#rl-form button[type=submit]")
    check("shared-room 3.3 m² can calculate through the selected source", "3.3 m²" in popup.locator("#rl-result").inner_text())
    context.close()
    browser.close()
server.shutdown()
if failures:
    raise SystemExit("Bulb brightness Chromium QA failed: " + ", ".join(failures))
print("Bulb brightness Chromium QA passed at 320, 390 and 1280 px, including shared-room handoff.")
